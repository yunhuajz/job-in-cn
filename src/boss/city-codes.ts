export function resolveBossCityCode(city: string): string | null {
  const trimmed = city.trim();
  const normalized = trimmed.replace(/(市|地区|特别行政区|盟|自治州|州)$/, '');
  return (
    BOSS_CITY_CODES[trimmed] ??
    BOSS_CITY_CODES[normalized] ??
    BOSS_CITY_CODES[`${normalized}市`] ??
    (/^\d{9}$/.test(trimmed) ? trimmed : null)
  );
}
