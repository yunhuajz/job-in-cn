export function resolveZhaopinCityCode(city: string): string | null {
  const trimmed = city.trim();
  const normalized = trimmed.replace(/(市|地区|特别行政区|盟|州)$/, '');
  return (
    ZHAOPIN_CITY_CODES[trimmed] ??
    ZHAOPIN_CITY_CODES[normalized] ??
    ZHAOPIN_CITY_CODES[`${normalized}市`] ??
    (/^\d+$/.test(trimmed) ? trimmed : null)
  );
}
