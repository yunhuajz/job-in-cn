export function resolveJob51CityCode(city: string): string | null {
  const trimmed = city.trim();
  const normalized = trimmed.replace(/(市|地区|特别行政区|盟|自治州|州)$/, '');
  return (
    JOB51_CITY_CODES[trimmed] ??
    JOB51_CITY_CODES[normalized] ??
    JOB51_CITY_CODES[`${normalized}市`] ??
    (/^\d{6}$/.test(trimmed) ? trimmed : null)
  );
}
